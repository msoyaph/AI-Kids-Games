/**
 * Level curve: a typical player who never grinds (only the wild spars on the path, the trainers
 * on the path, a few befriended friends, the suggested moves, Rest Stops) beats every Keeper on
 * Easy and Normal, for every partner choice. Hard is meant to be a challenge: it may take retries.
 * Writes reports/level-curve.md.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { Difficulty } from '../../src/core/types';
import { DEX } from '../../src/data/index';
import { STARTERS } from '../../src/data/species';
import { TRAINER_BY_ID } from '../../src/data/trainers';
import { simulateProgression, type ProgressionResult } from '../../src/sim/progression';

const SEEDS = 8;
const runs: Record<Difficulty, ProgressionResult[]> = { easy: [], normal: [], hard: [] };

interface Row { first: number; within2: number; within5: number; n: number; foe: number; teamAvg: number; teamMax: number }
function table(list: ProgressionResult[]) {
  const rows: Record<string, Row> = {};
  for (const r of list) for (const t of r.trainers) {
    const def = TRAINER_BY_ID[t.id]!;
    if (def.kind !== 'keeper' && def.kind !== 'rival' && !def.boss) continue;
    const row = (rows[t.id] ??= { first: 0, within2: 0, within5: 0, n: 0, foe: t.topFoeLevel, teamAvg: 0, teamMax: 0 });
    row.n++;
    if (t.attempts === 1) row.first++;
    if (t.attempts <= 2) row.within2++;
    if (t.attempts <= 5) row.within5++;
    row.teamAvg += t.teamLevels.reduce((a, b) => a + b, 0) / t.teamLevels.length;
    row.teamMax += Math.max(...t.teamLevels);
  }
  return rows;
}

describe('level curve without grinding', () => {
  it('plays every partner choice through every chapter on every difficulty', () => {
    for (const difficulty of ['easy', 'normal', 'hard'] as Difficulty[]) for (const starter of STARTERS) for (let s = 0; s < SEEDS; s++) {
      runs[difficulty].push(simulateProgression(DEX, starter, difficulty, 5000 + s * 13 + starter.length));
    }
    const pct = (a: number, b: number) => `${Math.round((a / b) * 100)}%`;
    const lines = ['# Agentmon level curve (no grinding)', '', `Generated by \`npm run test:sim\` (tests/sim/levelcurve.test.ts): ${SEEDS} runs for each of the 3 partners on each difficulty. The model player only spars what is on the path, befriends a few friends, takes the suggested moves and rests at Rest Stops. Losing sends it to a Rest Stop to try again, like the game.`, ''];
    for (const difficulty of ['easy', 'normal', 'hard'] as Difficulty[]) {
      const battles = runs[difficulty].reduce((a, r) => a + r.battles, 0) / runs[difficulty].length;
      lines.push(`## ${difficulty[0]!.toUpperCase()}${difficulty.slice(1)} (about ${Math.round(battles)} spars per playthrough)`, '', '| Spar | Their top level | Team average | Team best | Won first try | Within 2 tries |', '|---|---|---|---|---|---|');
      for (const [id, r] of Object.entries(table(runs[difficulty]))) {
        const t = TRAINER_BY_ID[id]!;
        lines.push(`| ${t.name} (${t.title}) | ${r.foe} | ${(r.teamAvg / r.n).toFixed(1)} | ${(r.teamMax / r.n).toFixed(1)} | ${pct(r.first, r.n)} | ${pct(r.within2, r.n)} |`);
      }
      lines.push('');
    }
    mkdirSync('reports', { recursive: true });
    writeFileSync('reports/level-curve.md', lines.join('\n'));
    expect(runs.normal).toHaveLength(SEEDS * 3);
  });

  for (const difficulty of ['easy', 'normal'] as Difficulty[]) {
    it(`${difficulty}: every Keeper, rival and boss spar is usually won first try (≥ 70%) and nearly always within two (≥ 95%)`, () => {
      for (const [id, r] of Object.entries(table(runs[difficulty]))) {
        expect(r.first / r.n, `${id} first try`).toBeGreaterThanOrEqual(0.7);
        expect(r.within2 / r.n, `${id} within 2`).toBeGreaterThanOrEqual(0.95);
      }
    });
  }

  it('hard: a real challenge, but no Keeper is a wall (beaten within five tries in ≥ 75% of runs)', () => {
    for (const [id, r] of Object.entries(table(runs.hard))) expect(r.within5 / r.n, id).toBeGreaterThanOrEqual(0.75);
  });

  it('the team grows from level 5 to the 40s by the last Beacon on Normal', () => {
    for (const r of runs.normal) expect(Math.max(...r.finalLevels)).toBeGreaterThanOrEqual(40);
  });
});
