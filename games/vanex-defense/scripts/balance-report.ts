// Full bot balance report → docs/reports/balance.md (and the console).
//   npm run balance-report            (~5 minutes: 18 maps × 12 bot runs)
//   npm run balance-report -- w4m3    one map
// Tables: campaign baseline (good bot, no hero/abilities/research — the hardest
// case, enforced by the balance tests), casual bot on Story, Expert with three
// kits, and challenge-medal achievability per map.
import { mkdirSync, writeFileSync } from 'node:fs';
import { starsFor, type Difficulty } from '../src/data/difficulty';
import { CAMPAIGN_MAPS } from '../src/data/maps';
import { bonusesFrom, RESEARCH_IDS } from '../src/data/research';
import { TUNING, type AbilityId, type ModifierId } from '../src/data/tuning';
import { simulate, type SimResult, type SimSetup } from '../src/sim/autoplay';

const only = process.argv.slice(2).find((a) => /^w\dm\d$/.test(a));
const maps = CAMPAIGN_MAPS.filter((m) => !only || m.id === only);
const STARTER: SimSetup = { hero: 'vanguard', abilities: ['meteor'] };
const fullResearch = Object.fromEntries(RESEARCH_IDS.map((id) => [id, TUNING.research[id]!.cost.length]));
const FULL: SimSetup = { hero: 'vanguard', abilities: ['meteor', 'chrono', 'funds'] as AbilityId[], bonuses: bonusesFrom(fullResearch) };
const MODS: ModifierId[] = ['iron', 'pure', 'budget', 'nocombo', 'speed'];

const cell = (r: SimResult): string => (r.won ? `✅ ${r.lives}/${r.maxLives}` : `❌ w${r.wave}`);
const stars = (r: SimResult): string => (r.won ? '★'.repeat(starsFor(r.lives, r.maxLives)) + '☆'.repeat(3 - starsFor(r.lives, r.maxLives)) : '—');
const run = (id: string, d: Difficulty, setup: SimSetup = {}, skill: 'good' | 'casual' = 'good'): SimResult => simulate(CAMPAIGN_MAPS.find((m) => m.id === id)!, d, { seed: 1, skill, ...setup });

const t0 = Date.now();
const lines: string[] = [];
const out = (s = ''): void => {
  lines.push(s);
  console.log(s);
};
const wins: Record<string, number> = {};
const tally = (k: string, r: SimResult): SimResult => {
  wins[k] = (wins[k] ?? 0) + (r.won ? 1 : 0);
  return r;
};

out('# Vanex Defense — bot balance report');
out();
out(`Generated by \`npm run balance-report\` (seed 1). Lives shown as left/max; ❌ wN = lost at wave N.`);
out('Baseline = good bot with **no** hero, abilities or research (strictly harder than real play; enforced by `npm test`).');
out('Starter kit = Vanguard + Crystal Meteor (what a new player has). Full kit = Vanguard + all 3 abilities + every research node maxed.');
out();
out('## Campaign');
out();
out('| Map | Story | Normal | Hard | Casual bot, Story |');
out('|---|---|---|---|---|');
for (const m of maps) {
  const s = tally('story', run(m.id, 'easy'));
  const n = tally('normal', run(m.id, 'normal'));
  const h = tally('hard', run(m.id, 'hard'));
  const c = tally('casual', run(m.id, 'easy', {}, 'casual'));
  out(`| ${m.id} ${m.name} | ${cell(s)} | ${cell(n)} | ${cell(h)} | ${cell(c)} ${stars(c)} |`);
}
out(`| **Wins** | ${wins.story}/${maps.length} | ${wins.normal}/${maps.length} | ${wins.hard}/${maps.length} | ${wins.casual}/${maps.length} |`);
out();
out('## Expert (report only)');
out();
out('| Map | Baseline | Starter kit | Full kit |');
out('|---|---|---|---|');
for (const m of maps) {
  const a = tally('xbase', run(m.id, 'expert'));
  const b = tally('xstart', run(m.id, 'expert', STARTER));
  const c = tally('xfull', run(m.id, 'expert', FULL));
  out(`| ${m.id} ${m.name} | ${cell(a)} | ${cell(b)} | ${cell(c)} |`);
}
out(`| **Wins** | ${wins.xbase}/${maps.length} | ${wins.xstart}/${maps.length} | ${wins.xfull}/${maps.length} |`);
out();
out('## Challenge medals (Normal, good bot, starter kit)');
out();
out('A failed cell is retried with the full kit (→): every medal must be earnable on every map once research is done.');
out();
out(`| Map | ${MODS.map((x) => x[0]!.toUpperCase() + x.slice(1)).join(' | ')} |`);
out(`|---|${MODS.map(() => '---').join('|')}|`);
for (const m of maps) {
  const cells = MODS.map((x) => {
    const r = tally(`mod_${x}`, run(m.id, 'normal', { ...STARTER, modifiers: [x] }));
    if (r.won) return cell(r);
    return `${cell(r)} → ${cell(tally(`modfull_${x}`, run(m.id, 'normal', { ...FULL, modifiers: [x] })))}`;
  });
  out(`| ${m.id} ${m.name} | ${cells.join(' | ')} |`);
}
out(`| **Starter kit** | ${MODS.map((x) => `${wins[`mod_${x}`] ?? 0}/${maps.length}`).join(' | ')} |`);
out(`| **With research** | ${MODS.map((x) => `${(wins[`mod_${x}`] ?? 0) + (wins[`modfull_${x}`] ?? 0)}/${maps.length}`).join(' | ')} |`);
out();
out(`_${maps.length * 12}+ bot runs in ${Math.round((Date.now() - t0) / 1000)} s._`);
if (!only) {
  mkdirSync('docs/reports', { recursive: true });
  writeFileSync('docs/reports/balance.md', lines.join('\n') + '\n');
  console.log('\nWrote docs/reports/balance.md');
}
