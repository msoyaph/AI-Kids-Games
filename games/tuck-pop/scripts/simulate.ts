// npm run sim [-- --casual=N --strong=N --json]
// Plays many games with the casual and strong bots through the real rules, and writes the
// balance report to reports/sim.md (percentiles of play time, score and moves per mode, dealer
// counters). The CI-sized checks are in tests/unit/balance.test.ts.
import { mkdirSync, writeFileSync } from 'node:fs';
import { Rng } from '../src/core/rng';
import { newStats } from '../src/sim/dealer';
import { collectStats, newGame, type Difficulty, type Mode } from '../src/sim/game';
import { playOut, type BotKind, type Played } from '../src/sim/bot';

const arg = (name: string, fallback: number) => Number(process.argv.find(a => a.startsWith(`--${name}=`))?.split('=')[1] ?? fallback);
const casualN = arg('casual', 20000), strongN = arg('strong', 400);

interface Run { label: string; mode: Mode; difficulty: Difficulty; kind: BotKind; n: number }
const runs: Run[] = [
  { label: 'Casual, Classic Normal', mode: 'classic', difficulty: 'normal', kind: 'casual', n: casualN },
  { label: 'Casual, Classic Easy', mode: 'classic', difficulty: 'easy', kind: 'casual', n: casualN },
  { label: 'Casual, Relax', mode: 'relax', difficulty: 'easy', kind: 'casual', n: Math.round(casualN / 4) },
  { label: 'Strong, Classic Normal', mode: 'classic', difficulty: 'normal', kind: 'strong', n: strongN },
  { label: 'Strong, Classic Easy', mode: 'classic', difficulty: 'easy', kind: 'strong', n: Math.round(strongN / 8) },
];

const pct = (xs: number[], p: number) => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(p * s.length))] ?? 0; };
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
const min = (s: number) => (s / 60).toFixed(1);

const lines: string[] = ['# Tuck Pop balance report', '', `Generated by \`npm run sim\` (${new Date().toISOString().slice(0, 10)}). Time is estimated from a per-move model (src/sim/bot.ts moveSeconds: about 3.3 s per move).`, ''];
lines.push('| Run | Games | Avg min | p10 / p50 / p90 min | Avg score | p50 / p90 score | Avg moves | Capped | Board clears/game | Dealer: draws/deal, built % |', '|---|---|---|---|---|---|---|---|---|---|');
const summary: Record<string, unknown> = {};
for (const run of runs) {
  const stats = newStats(); collectStats(stats);
  const played: Played[] = [];
  const t0 = Date.now();
  for (let i = 0; i < run.n; i++) {
    const seed = 1000 + i;
    played.push(playOut(newGame({ mode: run.mode, difficulty: run.difficulty, seed }), run.kind, new Rng(seed * 7 + 3)));
  }
  collectStats(null);
  const secs = played.map(p => p.seconds), scores = played.map(p => p.score);
  const row = { games: run.n, avgMin: mean(secs) / 60, p10: pct(secs, 0.1) / 60, p50: pct(secs, 0.5) / 60, p90: pct(secs, 0.9) / 60, avgScore: mean(scores), p50Score: pct(scores, 0.5), p90Score: pct(scores, 0.9), avgMoves: mean(played.map(p => p.moves)), capped: played.filter(p => p.capped).length, clears: mean(played.map(p => p.boardClears)), drawsPerDeal: stats.draws / Math.max(1, stats.deals), builtPct: (100 * stats.built) / Math.max(1, stats.deals), ms: Date.now() - t0 };
  summary[run.label] = row;
  lines.push(`| ${run.label} | ${run.n} | ${row.avgMin.toFixed(1)} | ${row.p10.toFixed(1)} / ${row.p50.toFixed(1)} / ${row.p90.toFixed(1)} | ${Math.round(row.avgScore)} | ${row.p50Score} / ${row.p90Score} | ${Math.round(row.avgMoves)} | ${row.capped} | ${row.clears.toFixed(2)} | ${row.drawsPerDeal.toFixed(2)}, ${row.builtPct.toFixed(1)}% |`);
  console.log(`${run.label}: ${run.n} games in ${(row.ms / 1000).toFixed(1)} s · avg ${min(mean(secs))} min (p50 ${min(pct(secs, 0.5))}) · avg score ${Math.round(row.avgScore)} · avg moves ${Math.round(row.avgMoves)} · capped ${row.capped}`);
}
mkdirSync('reports', { recursive: true });
writeFileSync('reports/sim.md', lines.join('\n') + '\n');
if (process.argv.includes('--json')) console.log(JSON.stringify(summary, null, 2));
