/**
 * Pacing model: the bot's real-time accounting (clock time while playing + paused time in
 * menus, dialogue, the fishing reel, festivals, cutscenes) estimates how long year one takes.
 * Target: about 7–8 hours to the finale. Writes reports/pacing.md with per-season estimates
 * and how the total shifts with bedtime (the biggest unknown until real playtests).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { useMemoryStorage } from '../../src/core/storage';
import { FINALE_DAY } from '../../src/data/boards';
import { SEASON_NAMES } from '../../src/sim/state';
import { TUNING } from '../../src/tuning';
import { Bot, MPS, type DayLog } from './bot';

useMemoryStorage();

const SEEDS = [2026, 11, 777];
const hh = (m: number) => `${Math.floor(m / 60) % 24}:${String(Math.round(m % 60)).padStart(2, '0')}`;
const fmt = (h: number) => h.toFixed(2);

interface Run {
  seed: number;
  days: DayLog[];
  finale: number;
  faints: number;
  skills: Record<string, number>;
  boardDays: Record<string, number>;
}

/** Real hours for a run if every non-festival day ended at `bed` instead (minutes). */
function hoursAtBedtime(r: Run, bed: number | null): number {
  let sec = 0;
  for (const d of r.days) sec += bed === null || d.did.some((x) => x.startsWith('festival') || x === 'FINALE') ? d.realSec : d.realSec + (bed - d.bed) / MPS;
  return sec / 3600;
}

describe('pacing model', () => {
  it('year one lands near 7–8 hours', () => {
    const runs: Run[] = [];
    for (const seed of SEEDS) {
      const bot = new Bot(seed);
      const boardDays: Record<string, number> = {};
      while (bot.finaleDay < 0 && bot.sim.state.day <= FINALE_DAY + 5) {
        const before = bot.sim.state.story.done.length;
        bot.playDay();
        for (const b of bot.sim.state.story.done.slice(before)) boardDays[b] = bot.sim.state.day;
      }
      runs.push({ seed, days: bot.days, finale: bot.finaleDay, faints: bot.faints, skills: bot.skillLevels(), boardDays });
    }
    const avg = (f: (r: Run) => number) => runs.reduce((t, r) => t + f(r), 0) / runs.length;
    const season = (r: Run, s: number) => r.days.filter((d) => Math.min(3, Math.floor(d.day / TUNING.seasonDays)) === s).reduce((t, d) => t + d.realSec, 0) / 3600;
    const paused = (r: Run) => r.days.reduce((t, d) => t + d.pausedSec, 0) / 3600;
    const bedAvg = (r: Run) => r.days.filter((d) => !d.did.some((x) => x === 'FINALE')).reduce((t, d) => t + d.bed, 0) / r.days.length;
    const total = avg((r) => hoursAtBedtime(r, null));
    const lines = [
      '# Cliff Valley — pacing model',
      '',
      `Generated by \`npm run pacing\` from ${runs.length} headless bot playthroughs (seeds ${SEEDS.join(', ')}).`,
      '',
      '**How it works.** The bot plays the real sim rules (energy, shop hours, seasons, money, bag space) and pays',
      `for everything in time: walking (route length × ${'1.35'} wander factor at walking speed), tool swings, and`,
      'paused-clock moments (reading mail, shop menus, chatting, gifts, the fishing reel, festivals, cutscenes).',
      `Real time = clock time while playing (a full day 6:00 → 2:00 is ${TUNING.dayRealSeconds / 60} real minutes) + paused time.`,
      'The bot goes to bed between about 9:30 and 11 pm (and around midnight one night in eight).',
      '',
      '## Year one',
      '',
      '| Season | Est. hours | Notes |',
      '| --- | --- | --- |',
      ...SEASON_NAMES.map((n, i) => `| ${n} | ${fmt(avg((r) => season(r, i)))} | ${['learning the farm, first boards, first mine trips', 'coop & animals, deep mine, Berry Bash', 'barn, kitchen, most boards repaired', 'last boards, Starlight Night, the grand reopening'][i]} |`),
      `| **Total to the finale** | **${fmt(total)}** | finale on day ${runs.map((r) => r.finale + 1).join(' / ')} (Winter 10 = day 40) |`,
      '',
      `Paused-clock share: ${fmt(avg(paused))} h. Average bedtime: ${hh(avg(bedAvg))}. Faints: ${runs.map((r) => r.faints).join(' / ')}.`,
      '',
      '## Bedtime sensitivity',
      '',
      'Year one is always 40 days (the finale is fixed on Winter 10), so total time mostly depends on how much of each day a kid plays.',
      '',
      '| Typical bedtime | Est. hours |',
      '| --- | --- |',
      ...[20 * 60, 21 * 60, 22 * 60, 23 * 60, 24 * 60, 25 * 60].map((b) => `| ${hh(b)} | ${fmt(avg((r) => hoursAtBedtime(r, b)))} |`),
      '',
      '## Per seed',
      '',
      '| Seed | Spring | Summer | Autumn | Winter | Total | Finale day | Boards repaired (day) | Skills at the end |',
      '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
      ...runs.map((r) => `| ${r.seed} | ${[0, 1, 2, 3].map((s) => fmt(season(r, s))).join(' | ')} | ${fmt(hoursAtBedtime(r, null))} | ${r.finale + 1} | ${Object.entries(r.boardDays).map(([b, d]) => `${b} ${d + 1}`).join(', ')} | ${Object.entries(r.skills).map(([k, v]) => `${k} ${v}`).join(', ')} |`),
      '',
      '## Caveats',
      '',
      '- The bot is a focused player: it always knows what the boards need. Real kids explore, decorate and chat more,',
      '  which adds time per day but not days — the year stays 40 days long.',
      '- Bedtime is the biggest lever. Calibrate with real sessions using `?playtest=1` and `npm run analyze-playtests`.',
      '',
    ];
    mkdirSync('reports', { recursive: true });
    writeFileSync('reports/pacing.md', lines.join('\n'));
    console.log(lines.join('\n'));
    for (const r of runs) expect(r.finale, `seed ${r.seed}`).toBeLessThanOrEqual(FINALE_DAY + 2);
    expect(total).toBeGreaterThan(6.5);
    expect(total).toBeLessThan(9.5);
  });
});
