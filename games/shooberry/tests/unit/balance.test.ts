// The bots' balance checks (the brief's definition of done): every Adventure level is beatable with
// the plants available, the casual bot 1-stars every level on its first or second try, and the
// Challenges and the Daily are winnable. Writes reports/balance.md and reports/pacing.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { LEVELS, WORLD_DEFS } from '../../src/data/levels';
import { CHALLENGES, dailyLevel } from '../../src/data/modes';
import { chooseSeeds, makeBot, type Skill } from '../../src/sim/bot';
import { createGame, run, stars } from '../../src/sim/game';
import type { LevelSpec } from '../../src/sim/types';

function play(level: LevelSpec & { plants: string[] }, skill: Skill, seed: number) {
  const g = createGame(level, level.fixedSeeds ?? chooseSeeds(level, level.plants, level.seedSlots, skill, seed), { seed });
  run(g, 1500, makeBot(skill, seed));
  return { won: g.result === 'won', stars: stars(g), time: g.t, umbrellas: g.stats.umbrellasUsed, seeds: g.cards.map(c => c.plant) };
}

/** Minutes a child spends around each try: choosing seeds, tips, the results screen. */
const AROUND_A_TRY = 0.9;
const rows: string[] = [], pace: { world: string; minutes: number }[] = [];
const usage: Record<string, number> = {};

for (const [wi, world] of WORLD_DEFS.entries()) {
  describe(`balance: ${world.id}`, () => {
    it('the good bot wins every level, and the casual bot wins each on its first or second try', () => {
      let minutes = 0;
      for (const level of LEVELS.filter(l => l.worldIndex === wi)) {
        const good = play(level, 'good', 1), c1 = play(level, 'casual', 1), c2 = c1.won ? c1 : play(level, 'casual', 2);
        for (const s of good.seeds) usage[s] = (usage[s] ?? 0) + 1;
        rows.push(`| ${level.id} | ${good.won ? `${good.stars}★` : 'lost'} | ${c1.won ? `${c1.stars}★ first try` : c2.won ? `${c2.stars}★ second try` : 'lost twice'} | ${Math.round(c1.time / 6) / 10} min | ${good.umbrellas} |`);
        minutes += c1.time / 60 + AROUND_A_TRY + (c1.won ? 0 : c2.time / 60 + AROUND_A_TRY);
        expect(good.won, `${level.id}: good bot`).toBe(true);
        expect(c2.won, `${level.id}: casual bot within two tries`).toBe(true);
      }
      pace.push({ world: world.id, minutes });
    });
  });
}

describe('balance: other modes', () => {
  it('every Challenge is winnable by both bots', () => {
    for (const c of CHALLENGES) {
      expect(play(c, 'good', 1).won, `${c.id} good`).toBe(true);
      const c1 = play(c, 'casual', 1);
      expect(c1.won || play(c, 'casual', 2).won, `${c.id} casual`).toBe(true);
    }
  });
  it('a week of Daily gardens are winnable by the casual bot with every plant', () => {
    const all = LEVELS.at(-1)!.plants;
    for (let d = 14; d <= 20; d++) { const daily = dailyLevel(`2026-10-${d}`, all); expect(play(daily, 'casual', 1).won || play(daily, 'casual', 2).won, daily.id).toBe(true); }
  });
  it('writes the reports', () => {
    mkdirSync(new URL('../../reports', import.meta.url), { recursive: true });
    const total = pace.reduce((a, p) => a + p.minutes, 0);
    writeFileSync(new URL('../../reports/balance.md', import.meta.url), [
      '# Balance (generated by tests/unit/balance.test.ts)', '',
      'Good bot: seed 1. Casual bot: slower decisions (1.1–1.9 s), fewer producers, random lane picks 20% of the time, skips good seeds now and then.', '',
      '| Level | Good bot | Casual bot | Casual first try | Umbrellas used (good) |', '|---|---|---|---|---|', ...rows, '',
      '## Seeds the good bot chose (levels)', '', Object.entries(usage).sort((a, b) => b[1] - a[1]).map(([id, n]) => `${id} ${n}`).join(', '), '',
    ].join('\n'));
    writeFileSync(new URL('../../reports/pacing.md', import.meta.url), [
      '# Pacing (generated by tests/unit/balance.test.ts)', '',
      `The casual bot's clock for every try (a lost try is played again), plus ${AROUND_A_TRY} min around each try for choosing seeds, tips and results.`, '',
      '| World | Minutes |', '|---|---|', ...pace.map(p => `| ${p.world} | ${Math.round(p.minutes)} |`), `| **Adventure** | **${Math.round(total)} (${(total / 60).toFixed(1)} h)** |`, '',
    ].join('\n'));
    expect(pace).toHaveLength(5);
  });
});
