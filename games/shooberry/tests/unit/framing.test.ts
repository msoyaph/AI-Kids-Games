// The board fills the screen (the owner's art direction: "the playing board fills at least 85% of
// the screen on phone landscape, tablet and desktop"). Measured against the play area: the screen
// minus the top bar, the card tray and the device's safe areas, none of which may cover the board.
// The board here is the playfield: the five beds plus the path in on the right, where critters are
// in play from the moment they come through the bushes.
// Upright tablets are the one exception: a 9 × 5 board can't fill a tall screen, so there it spans
// the width, with sky and garden above and below. The table of shares (also of the whole screen) is
// written to reports/framing.md.
import { mkdirSync, writeFileSync } from 'node:fs';
import * as THREE from 'three';
import { describe, expect, it } from 'vitest';
import { boardAspect, fitCamera, lean, PITCH_RANGE, project } from '../../src/render/camera';
import { BOARD_D, ENTRY_X } from '../../src/sim/board';
import { BOARD_ASPECT, layout, SMALLEST_PHONE, SUPPORTED_VIEWPORTS } from '../../src/ui/layout';

const cam = new THREE.PerspectiveCamera();
const rows: string[] = [];

function shares(w: number, h: number, insets?: Parameters<typeof layout>[2]) {
  const fit = fitCamera(cam, w, h, insets);
  const open = layout(w, h, insets).open;
  const pts = [[0, 0], [ENTRY_X, 0], [0, BOARD_D], [ENTRY_X, BOARD_D]].map(([x, z]) => project(cam, w, h, x!, 0, z!));
  const bx0 = Math.min(...pts.map(p => p.x)), bx1 = Math.max(...pts.map(p => p.x)), by0 = Math.min(...pts.map(p => p.y)), by1 = Math.max(...pts.map(p => p.y));
  return { pitch: (fit.pitch * 180) / Math.PI, lean: (lean(fit.pitch) * 180) / Math.PI, width: (bx1 - bx0) / open.w, height: (by1 - by0) / open.h, screen: ((bx1 - bx0) * (by1 - by0)) / (w * h) };
}

describe('framing', () => {
  for (const vp of [...SUPPORTED_VIEWPORTS, SMALLEST_PHONE]) {
    it(`the board fills the play area on a ${vp.name} (${vp.w}×${vp.h})`, () => {
      const s = shares(vp.w, vp.h, vp.insets);
      const upright = vp.h > vp.w;
      rows.push(`| ${vp.name} | ${vp.w}×${vp.h} | ${s.pitch.toFixed(1)}° | ${s.lean.toFixed(0)}° | ${(s.width * 100).toFixed(0)}% | ${(s.height * 100).toFixed(0)}% | ${(s.screen * 100).toFixed(0)}% |`);
      expect(s.width, 'width share').toBeGreaterThanOrEqual(0.85);
      if (!upright) expect(s.height, 'height share').toBeGreaterThanOrEqual(0.85);
    });
  }
  it("the layout's idea of the board's shape matches the camera", () => {
    for (const [deg, want] of [[PITCH_RANGE[1], BOARD_ASPECT[0]], [PITCH_RANGE[0], BOARD_ASPECT[1]]] as const) {
      const got = boardAspect(cam, (deg * Math.PI) / 180);
      expect(Math.abs(got / want - 1), `${deg}°: ${got.toFixed(2)}`).toBeLessThan(0.08);
    }
  });
  it('writes the table', () => {
    mkdirSync(new URL('../../reports', import.meta.url), { recursive: true });
    writeFileSync(new URL('../../reports/framing.md', import.meta.url), [
      '# Framing (generated by tests/unit/framing.test.ts)',
      '',
      'Board = the playfield: the five beds and the path in, where critters walk. Play area = the screen minus the top bar, the card tray and safe areas.',
      '',
      '| Screen | Size | Camera tilt | Character lean | Board / play-area width | Board / play-area height | Board / whole screen |',
      '|---|---|---|---|---|---|---|',
      ...rows,
      '',
    ].join('\n'));
    expect(rows.length).toBe(SUPPORTED_VIEWPORTS.length + 1);
  });
});
