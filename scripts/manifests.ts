// npm run manifests [-- --check]
// Reads every games/<slug>/game.json, validates it, and writes what is generated from it:
//   apps/site/src/data/games.generated.ts  the website's game registry
//   README.md (between the GAMES markers)  the game showcase table
//   llms.txt                               the summary for AI assistants, with the approved community games
//                                          (the site build writes its own, plus llms-full.txt, for the
//                                          address it is deployed at)
//   apps/mcp/src/data/catalog.generated.json  the AI Kids Games app's catalog: released games only ("Ready
//                                          to play"), with their verified builds, plus approved community games
// --check fails (for CI) when any generated file is out of date instead of writing it.
import { existsSync,readFileSync,writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ageText,bySiteOrder,readManifests,validateManifest,type Manifest } from './lib/manifest';
import { buildImportsPath,readJson,root,site,type BuildImports } from './lib/repo';
import { buildCatalog } from './lib/catalog';
import type { Game } from '../apps/site/src/data/games';
import { PUBLIC_ORIGIN } from '../apps/site/src/data/site';
import { llmsText } from '../apps/site/src/seo/llms';
import { communityEntries } from '../apps/site/scripts/generate-community';

const check = process.argv.includes('--check');
const all = readManifests();
const errors = all.flatMap(m => validateManifest(m));
if (errors.length) { console.error(`Game manifests are invalid:\n${errors.map(error => `  • ${error}`).join('\n')}`); process.exit(1); }
// Games still "In development" are validated but never listed.
const manifests = all.filter(m => m.site.status !== 'In development');
manifests.sort(bySiteOrder);

const entry = (m: Manifest): Game => ({
  slug: m.slug,title: m.title,tagline: m.tagline,description: m.shortDescription,version: m.version,
  categories: m.genres,tags: m.tags,keywords: m.keywords,ageGuidance: ageText(m),minAge: m.minAge,contentNotes: m.contentNotes,
  estimatedPlayTime: m.playTime,quickStart: m.controls.quickStart,controls: { types: m.controls.types,howToPlay: m.controls.howToPlay },
  supportedDevices: m.devices,orientation: m.orientation,requirements: m.requirements ?? [],
  coverLayers: m.site.coverLayers,releaseDate: m.site.releaseDate,featured: m.site.featured,accentColor: m.site.accentColor,status: m.site.status as Game['status'],
  storage: { prefix: m.storage.prefix,keys: m.storage.keys },safety: m.safety,license: m.license
});
function registry(list: Manifest[]) {
  const entries = list.map(entry);
  return `// Generated by \`npm run manifests\` from games/<slug>/game.json. Do not edit by hand.\nimport type { Game } from './games';\n\nexport const generatedGames: Game[] = ${JSON.stringify(entries,null,2)};\n`;
}

const cell = (text: string) => text.replace(/\|/g,'\\|');
function table(list: Manifest[]) {
  // The README's simple table; the full showcase (covers, previews, Play links) is the website.
  const rows = list.map(m => `| **${m.title}** | ${cell(m.shortDescription)} | ${ageText(m)} | [games/${m.slug}](games/${m.slug}) |`);
  return ['<!-- GAMES:START (generated by npm run manifests) -->','| Game | What it is | Ages | Source |','|---|---|---|---|',...rows,'<!-- GAMES:END -->'].join('\n');
}

const approvedCommunity = communityEntries('production');
const outputs: [string,string][] = [
  [resolve(site,'src/data/games.generated.ts'),registry(manifests)],
  [resolve(root,'llms.txt'),llmsText(PUBLIC_ORIGIN,manifests.map(entry),approvedCommunity)],
  [resolve(root,'apps/mcp/src/data/catalog.generated.json'),`${JSON.stringify(buildCatalog(manifests,approvedCommunity,readJson<BuildImports>(buildImportsPath).games),null,2)}\n`]
];
const readme = resolve(root,'README.md');
if (existsSync(readme)) {
  const current = readFileSync(readme,'utf8');
  const next = current.replace(/<!-- GAMES:START[\s\S]*?<!-- GAMES:END -->/,table(manifests))
    .replace(/alt="Games: \d+" src="https:\/\/img\.shields\.io\/badge\/games-\d+-/,`alt="Games: ${manifests.length}" src="https://img.shields.io/badge/games-${manifests.length}-`);
  outputs.push([readme,next]);
}
const stale = outputs.filter(([file,text]) => !existsSync(file) || readFileSync(file,'utf8') !== text).map(([file]) => file.slice(root.length));
if (check) {
  if (stale.length) { console.error(`Generated files are out of date: ${stale.join(', ')}. Run npm run manifests.`); process.exit(1); }
  console.log(`Manifests valid and generated files up to date (${manifests.length} games listed${all.length > manifests.length ? `, ${all.length-manifests.length} in development` : ''}).`);
} else {
  for (const [file,text] of outputs) writeFileSync(file,text);
  console.log(`${all.length} manifests valid, ${manifests.length} listed. ${stale.length ? `Updated ${stale.join(', ')}.` : 'Nothing changed.'}`);
}
