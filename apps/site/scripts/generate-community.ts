// Writes src/data/community.generated.ts (git-ignored): the community games this build of the
// website shows, from community/*/game.json, with each game's address on the play origin. It is
// generated at build time, not committed, because a community pull request may change only its
// own folder. Runs before every build, dev server and test run (package.json, vitest globalSetup).
// Production: approved, listed, unchanged games only (scripts/lib/community.ts servedCommunity).
import { existsSync,readdirSync,writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { communityMode,playUrl,servedCommunity } from '../../../scripts/lib/community';
import { validCommunityManifests } from '../../../scripts/lib/manifest';
import { communityDir } from '../../../scripts/lib/repo';
import type { Game } from '../src/data/games';

const publicDir = resolve(import.meta.dirname,'../public');

/** The community games a build serves; `mode` defaults to this build's (scripts/lib/community.ts communityMode). */
export function communityEntries(mode = communityMode()): Game[] {
  const { valid,invalid } = validCommunityManifests();
  for (const { slug,why } of invalid) console.warn(`Community game ${slug} left out: ${why}`);
  return servedCommunity(valid,mode,communityDir).served.map(({ manifest: m,preview }) => {
    const art = `/media/community/${m.slug}`, has = (file: string) => existsSync(resolve(publicDir,`.${art}/${file}`));
    const shots = existsSync(resolve(publicDir,`.${art}`)) ? readdirSync(resolve(publicDir,`.${art}`)).filter(file => /^shot-\d+\.webp$/.test(file)).sort().map(file => `${art}/${file}`) : [];
    return {
      slug: m.slug,title: m.title,version: m.version,tagline: m.tagline,description: m.shortDescription,
      categories: m.genres,tags: m.tags,keywords: m.keywords,ageGuidance: `Ages ${m.ageRange}`,minAge: m.minAge,contentNotes: m.contentNotes,
      estimatedPlayTime: m.playTime,quickStart: m.controls.quickStart,controls: { types: m.controls.types,howToPlay: m.controls.howToPlay },
      supportedDevices: m.devices,orientation: m.orientation,requirements: m.requirements ?? [],coverLayers: [],
      releaseDate: m.approval?.date ?? m.submitted.date,featured: false,accentColor: m.accentColor ?? '#e7e3f7',status: 'Ready to play',
      storage: { prefix: m.storage.prefix,keys: m.storage.keys },safety: m.safety,license: m.license,
      community: {
        handle: m.creator.handle,playUrl: playUrl(m.slug,mode),preview,longDescription: m.longDescription,
        cover: has('cover.webp') ? `${art}/cover.webp` : '/media/community/placeholder.svg',shots,og: has('og.jpg') ? `${art}/og.jpg` : '/og/site.jpg'
      }
    } satisfies Game;
  });
}

/** The play origins the website may frame (its CSP frame-src). */
export const communityOrigins = (entries = communityEntries()) => [...new Set(entries.map(game => new URL(game.community!.playUrl).origin))];

export function writeCommunity() {
  const entries = communityEntries();
  writeFileSync(resolve(import.meta.dirname,'../src/data/community.generated.ts'),`// Generated by scripts/generate-community.ts from community/*/game.json (${communityMode()} build). Do not edit; not committed.\nimport type { Game } from './games';\n\nexport const generatedCommunity: Game[] = ${JSON.stringify(entries,null,2)};\n`);
  return entries;
}
/** vitest globalSetup */
export default function setup() { writeCommunity(); }
if (import.meta.url === `file://${process.argv[1]}`) { const entries = writeCommunity(); console.log(`Community games for this build (${communityMode()}): ${entries.length ? entries.map(game => `${game.slug}${game.community!.preview ? ' (preview)' : ''}`).join(', ') : 'none'}.`); }
